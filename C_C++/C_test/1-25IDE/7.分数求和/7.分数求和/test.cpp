//计算 1 / 1 - 1 / 2 + 1 / 3 - 1 / 4 + 1 / 5 - … + 1 / 99 - 1 / 100 的值，并打印出结果，（注：除法分为整数除法和
//浮点数除法，要计算出⼩数，得采⽤浮点数除法，浮点数除法的操作数中⾄少要保证有⼀个浮点数。）
#include <stdio.h>

int main() {
	float num = 0;
	for (int i = 1; i < 101; i++) {
		if (0 == i % 2) {
			num -= 1.0 / i;
		}
		else {
			num += 1.0 / i;
		}
	}
	printf("%f\n", num);
	return 0;
}
